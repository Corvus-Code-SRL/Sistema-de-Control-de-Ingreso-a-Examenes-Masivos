        DB::statement(
            'UPDATE public.gestion_periodo gp SET id_periodo = p.id_periodo '
            . 'FROM public.periodo p WHERE p.codigo = ' . $this->codeExpression('gp.nombre_periodo')
        );

        DB::unprepared(<<<'SQL'
ALTER TABLE public.gestion_periodo
    ALTER COLUMN id_gestion SET NOT NULL,
    ALTER COLUMN id_periodo SET NOT NULL,
    ADD CONSTRAINT fk_gestion_periodo_gestion
        FOREIGN KEY (id_gestion) REFERENCES public.gestion(id_gestion),
    ADD CONSTRAINT fk_gestion_periodo_periodo
        FOREIGN KEY (id_periodo) REFERENCES public.periodo(id_periodo),
    ADD CONSTRAINT unq_gestion_periodo UNIQUE (id_gestion, id_periodo),
    ADD CONSTRAINT chk_gestion_periodo_fechas
        CHECK (fecha_inicio IS NULL OR fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
    DROP COLUMN nombre_periodo,
    DROP COLUMN gestion;

CREATE UNIQUE INDEX unq_gestion_periodo_activo
    ON public.gestion_periodo (activo)
    WHERE activo;

CREATE INDEX idx_gestion_periodo_gestion ON public.gestion_periodo(id_gestion);
CREATE INDEX idx_gestion_periodo_periodo ON public.gestion_periodo(id_periodo);

