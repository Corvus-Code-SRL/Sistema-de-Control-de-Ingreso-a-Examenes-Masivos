        DB::statement('ALTER SEQUENCE periodo_id_periodo_seq RENAME TO gestion_periodo_id_gestion_periodo_seq');
        DB::statement('ALTER TABLE periodo RENAME TO gestion_periodo');
        DB::statement('ALTER TABLE gestion_periodo RENAME COLUMN id_periodo TO id_gestion_periodo');
        DB::statement('ALTER TABLE gestion_periodo RENAME CONSTRAINT pk_periodo TO pk_gestion_periodo');
        DB::statement('ALTER TABLE gestion_periodo DROP CONSTRAINT unq_periodo_nombre');

        DB::unprepared(<<<'SQL'
