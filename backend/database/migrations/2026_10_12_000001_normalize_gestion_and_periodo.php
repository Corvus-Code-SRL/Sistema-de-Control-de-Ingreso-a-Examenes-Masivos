/**
 * Separa la gestión (año académico) del período y normaliza ambos.
 *
 * Antes `periodo` guardaba la instancia («1-2026») con su año. Ahora:
 *   - `gestion`          el año (id_gestion, anio).
 *   - `periodo`          catálogo fijo (0 Anual, 1, 2, 3 Verano, 4 Invierno).
 *   - `gestion_periodo`  la instancia (1/2026): la antigua tabla `periodo`, renombrada. Conserva sus
 *                        filas y sus ids, así que `grupo` y `convocatoria_admision` no se remapean.
 *
 * El período activo deja de ser configuración: vive en gestion_periodo.activo, con un índice parcial
 * que impide más de uno. Esta migración activa una sola vez la fila que apunta
 * SCIEM_PERIODO_ACTIVO_ID (se lee con env(), por lo que `php artisan config:clear` debe ejecutarse
 * antes y la variable debe estar en el .env de quien corre la migración). Sin variable, o si su id no
 * existe, ningún período queda activo y se deja un aviso en el log.
 *
 * Antes de tocar nada verifica que cada fila antigua se pueda interpretar y aborta, con las filas
 * culpables, si algo no encaja. Toda la migración corre en una transacción.
 */
class NormalizeGestionAndPeriodo extends Migration
{
    /** nombre_periodo admite «N-AAAA» y «AAAA-N» (N entre 0 y 4), con «-» o «/». */
    private const NAME_N_FIRST = '^\\s*([0-4])\\s*[-/]\\s*([0-9]{4})\\s*$';
    private const NAME_YEAR_FIRST = '^\\s*([0-9]{4})\\s*[-/]\\s*([0-4])\\s*$';

    public function up()
