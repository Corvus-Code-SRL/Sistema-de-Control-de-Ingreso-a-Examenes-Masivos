    /**
     * Cada fila de `periodo` debe tener un nombre interpretable cuyo año coincida con `gestion`, un
     * año dentro del rango nuevo y una combinación (año, período) única. Si no, aborta con las filas.
     */
    private function assertLegacyDataCanBeNormalized(): void
    {
        $problems = [];

        $unreadable = DB::select(
            'SELECT id_periodo, nombre_periodo, gestion FROM periodo WHERE ' . $this->codeExpression('nombre_periodo')
            . ' IS NULL ORDER BY id_periodo'
        );
        $this->collect($problems, 'nombre_periodo no tiene la forma «N-AAAA» ni «AAAA-N» (N entre 0 y 4)', $unreadable);

        $outOfRange = DB::select(
            'SELECT id_periodo, nombre_periodo, gestion FROM periodo '
            . 'WHERE gestion NOT BETWEEN 2000 AND 2100 ORDER BY id_periodo'
        );
        $this->collect($problems, 'gestion fuera del rango 2000-2100 de la tabla gestion', $outOfRange);

        $yearMismatch = DB::select(
            'SELECT id_periodo, nombre_periodo, gestion FROM periodo WHERE ' . $this->codeExpression('nombre_periodo')
            . ' IS NOT NULL AND ' . $this->yearExpression('nombre_periodo') . ' <> gestion ORDER BY id_periodo'
        );
        $this->collect($problems, 'el año de nombre_periodo no coincide con gestion', $yearMismatch);

        $collisions = DB::select(
            'SELECT gestion, ' . $this->codeExpression('nombre_periodo') . ' AS codigo, count(*) AS filas, '
            . 'string_agg(id_periodo::text, \',\' ORDER BY id_periodo) AS ids FROM periodo '
            . 'WHERE ' . $this->codeExpression('nombre_periodo') . ' IS NOT NULL '
            . 'GROUP BY gestion, ' . $this->codeExpression('nombre_periodo') . ' HAVING count(*) > 1'
        );
        $this->collect($problems, 'dos períodos resolverían al mismo (año, período)', $collisions);

        $duplicateGroups = DB::select(
            'SELECT id_carrera, id_materia, num_grupo, id_periodo, count(*) AS filas, '
            . 'string_agg(id_grupo::text, \',\' ORDER BY id_grupo) AS ids FROM grupo '
            . 'GROUP BY id_carrera, id_materia, num_grupo, id_periodo HAVING count(*) > 1'
        );
        $this->collect(
            $problems,
            'grupos que chocarían en unq_grupo al quitar grupo.gestion (mismo par, número y período)',
            $duplicateGroups
        );

        if ($problems !== []) {
            throw new RuntimeException(
                "No se normalizaron gestion y periodo; no se modificó nada.\n" . implode("\n", $problems)
            );
        }

        $this->warnAboutDiscardedColumns();
    }

    /** grupo.gestion y convocatoria_admision.gestion eran redundantes: si difieren, se avisa y se descartan. */
    private function warnAboutDiscardedColumns(): void
    {
        $groups = DB::select(
            'SELECT g.id_grupo, g.gestion AS grupo_gestion, p.gestion AS periodo_gestion '
            . 'FROM grupo g JOIN periodo p ON p.id_periodo = g.id_periodo '
            . 'WHERE g.gestion <> p.gestion::text ORDER BY g.id_grupo'
        );

        $calls = DB::select(
            'SELECT c.id_admision, c.gestion AS convocatoria_gestion, p.gestion AS periodo_gestion '
            . 'FROM convocatoria_admision c JOIN periodo p ON p.id_periodo = c.id_periodo '
            . 'WHERE c.gestion <> p.gestion::text ORDER BY c.id_admision'
        );

        if ($groups !== []) {
            Log::warning('gestion_periodo: grupo.gestion distinto de periodo.gestion; se conserva el del período.', [
                'grupos' => count($groups),
                'ids' => array_map(fn ($row) => $row->id_grupo, array_slice($groups, 0, 20)),
            ]);
        }

        if ($calls !== []) {
            Log::warning(
                'gestion_periodo: convocatoria_admision.gestion distinta de periodo.gestion; se conserva la del período.',
                ['convocatorias' => count($calls)]
            );
        }
    }

    private function activateConfiguredPeriod(): void
    {
        $configured = env('SCIEM_PERIODO_ACTIVO_ID');

        if ($configured === null || $configured === '' || ! ctype_digit((string) $configured) || (int) $configured < 1) {
            Log::warning('gestion_periodo: SCIEM_PERIODO_ACTIVO_ID no está definida; ningún período quedó activo.');

            return;
        }

        $activated = DB::table('gestion_periodo')
            ->where('id_gestion_periodo', (int) $configured)
            ->update(['activo' => true]);

        if ($activated === 0) {
            Log::warning(
                'gestion_periodo: SCIEM_PERIODO_ACTIVO_ID no corresponde a ningún período; ninguno quedó activo.',
                ['id' => (int) $configured]
            );
        }
    }

    /** Expresión SQL con el código de período (0-4) que expresa el nombre, o NULL si no se entiende. */
    private function codeExpression(string $column): string
    {
        return sprintf(
            "(CASE WHEN %1\$s ~ '%2\$s' THEN substring(%1\$s from '%2\$s')::smallint "
            . "WHEN %1\$s ~ '%3\$s' THEN substring(%1\$s from '[-/]\\s*([0-4])\\s*\$')::smallint END)",
            $column,
            self::NAME_N_FIRST,
            self::NAME_YEAR_FIRST
        );
    }

    /** Año que expresa el nombre (solo se evalúa cuando el nombre se entiende). */
    private function yearExpression(string $column): string
    {
        return sprintf(
            "(CASE WHEN %1\$s ~ '%2\$s' THEN (regexp_match(%1\$s, '%2\$s'))[2]::smallint "
            . "ELSE (regexp_match(%1\$s, '%3\$s'))[1]::smallint END)",
            $column,
            self::NAME_N_FIRST,
            self::NAME_YEAR_FIRST
        );
    }

    private function collect(array &$problems, string $title, array $rows): void
    {
        if ($rows === []) {
            return;
        }

        $detail = array_map(fn ($row) => json_encode($row, JSON_UNESCAPED_UNICODE), array_slice($rows, 0, 20));

        $problems[] = sprintf('- %s (%d filas): %s', $title, count($rows), implode('; ', $detail));
    }
}
